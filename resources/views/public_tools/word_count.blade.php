    <script>
        function recalcWords() {
            const raw = document.getElementById('wc-input').value || '';
            const trimmed = raw.trim();
            const words = trimmed ? trimmed.split(/\s+/).filter(Boolean).length : 0;
            const chars = raw.length;
            const noSpace = raw.replace(/\s+/g, '').length;
            const paras = trimmed ? trimmed.split(/\n\s*\n/).filter(p => p.trim().length > 0).length : 0;
            const sents = trimmed ? trimmed.split(/[.!?]+/).filter(s => s.trim().length > 2).length : 0;
            const p15 = words > 0 ? Math.max(1, Math.ceil(words / 330)) : 0;
            const p20 = words > 0 ? Math.max(1, Math.ceil(words / 250)) : 0;
            const mins = Math.max(0, Math.ceil(words / 125));

            document.getElementById('wc-words').textContent = words.toLocaleString('id-ID');
            document.getElementById('wc-speak').textContent = `~${mins} menit baca`;
            document.getElementById('wc-chars').textContent = chars.toLocaleString('id-ID');
            document.getElementById('wc-nospace').textContent = `${noSpace.toLocaleString('id-ID')} tanpa spasi`;
            document.getElementById('wc-paras').textContent = paras;
            document.getElementById('wc-sents').textContent = `${sents} kalimat`;
            document.getElementById('wc-pages15').textContent = `${p15} hal`;
            document.getElementById('wc-pages20').textContent = `Spasi 1,5 · (${p20} hal spasi 2)`;

            const badge = document.getElementById('wc-badge');
            badge.classList.remove('ok', 'warn');
            if (words === 0) {
                badge.textContent = 'Standar abstrak skripsi Indonesia umumnya 150–250 kata.';
            } else if (words >= 150 && words <= 250) {
                badge.classList.add('ok');
                badge.textContent = `Ideal untuk Abstrak (${words} kata, tepat di rentang 150–250 kata).`;
            } else if (words < 150) {
                badge.classList.add('warn');
                badge.textContent = `Terlalu singkat untuk Abstrak (${words} kata — kurang ${150 - words} kata lagi ke batas 150).`;
            } else if (words <= 350) {
                badge.classList.add('warn');
                badge.textContent = `Sedikit melewati batas Abstrak (${words} kata — melebihi 250 kata).`;
            } else {
                badge.classList.add('ok');
                badge.textContent = `Naskah Bab/Paragraf (${words.toLocaleString('id-ID')} kata ≈ ${p15} halaman A4 spasi 1,5).`;
            }
        }
    </script>
